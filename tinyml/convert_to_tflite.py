"""
Convert Keras Model to TensorFlow Lite for ESP32

Includes quantization for optimal size and performance.
"""

import tensorflow as tf
import numpy as np
import os
import json


def convert_to_tflite(model_path, output_path, quantize=False):
    """
    Convert Keras model to TensorFlow Lite
    
    Args:
        model_path: Path to .h5 model
        output_path: Path to save .tflite model
        quantize: Whether to apply quantization
    """
    print(f"\n=== Converting {model_path} ===")
    
    # Load Keras model
    model = tf.keras.models.load_model(model_path)
    
    # Create TFLite converter
    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    
    if quantize:
        print("Applying quantization...")
        # Dynamic range quantization (reduces size by ~4x)
        converter.optimizations = [tf.lite.Optimize.DEFAULT]
        
        # Optional: Full integer quantization (requires representative dataset)
        # converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
        # converter.inference_input_type = tf.int8
        # converter.inference_output_type = tf.int8
    
    # Convert
    tflite_model = converter.convert()
    
    # Save
    with open(output_path, 'wb') as f:
        f.write(tflite_model)
    
    # Get size
    size_kb = len(tflite_model) / 1024
    print(f"✓ Converted model saved: {output_path}")
    print(f"✓ Size: {size_kb:.2f} KB")
    
    return tflite_model, size_kb


def test_tflite_model(tflite_path, test_input):
    """
    Test TFLite model inference
    
    Args:
        tflite_path: Path to .tflite model
        test_input: Sample input for testing
    """
    print(f"\n=== Testing {tflite_path} ===")
    
    # Load TFLite model
    interpreter = tf.lite.Interpreter(model_path=tflite_path)
    interpreter.allocate_tensors()
    
    # Get input/output details
    input_details = interpreter.get_input_details()
    output_details = interpreter.get_output_details()
    
    print(f"Input shape: {input_details[0]['shape']}")
    print(f"Output shape: {output_details[0]['shape']}")
    
    # Run inference
    interpreter.set_tensor(input_details[0]['index'], test_input)
    interpreter.invoke()
    output = interpreter.get_tensor(output_details[0]['index'])
    
    print(f"✓ Inference successful")
    print(f"  Input: {test_input[0, -1, :]}  (last timestep)")
    print(f"  Output: {output[0][0]:.2f}%")
    
    return output


def generate_c_array(tflite_model, output_path='models/model_data.h'):
    """
    Generate C header file with model data
    
    This allows embedding the model directly in ESP32 firmware
    """
    print(f"\n=== Generating C Header ===")
    
    # Convert to hex array
    hex_array = ', '.join([f'0x{b:02x}' for b in tflite_model])
    
    # Generate header file
    header = f"""// Auto-generated TensorFlow Lite model
// Generated by convert_to_tflite.py

#ifndef MODEL_DATA_H
#define MODEL_DATA_H

const unsigned char model_data[] = {{
{hex_array}
}};

const unsigned int model_data_len = {len(tflite_model)};

#endif  // MODEL_DATA_H
"""
    
    with open(output_path, 'w') as f:
        f.write(header)
    
    print(f"✓ C header saved: {output_path}")
    print(f"✓ Array size: {len(tflite_model)} bytes")


def generate_arduino_code(norm_params):
    """Generate Arduino inference code"""
    
    code = f"""// TinyML Inference Code for ESP32
// Auto-generated by convert_to_tflite.py

#include <TensorFlowLite_ESP32.h>
#include "tensorflow/lite/micro/all_ops_resolver.h"
#include "tensorflow/lite/micro/micro_error_reporter.h"
#include "tensorflow/lite/micro/micro_interpreter.h"
#include "tensorflow/lite/schema/schema_generated.h"
#include "model_data.h"

// Normalization parameters
const float feature_mins[] = {{{', '.join([f'{x:.4f}f' for x in norm_params['mins']])}}};
const float feature_ranges[] = {{{', '.join([f'{x:.4f}f' for x in norm_params['ranges']])}}};

// TFLite globals
namespace {{
  tflite::ErrorReporter* error_reporter = nullptr;
  const tflite::Model* model = nullptr;
  tflite::MicroInterpreter* interpreter = nullptr;
  TfLiteTensor* input = nullptr;
  TfLiteTensor* output = nullptr;
  
  constexpr int kTensorArenaSize = 4 * 1024;  // 4KB
  uint8_t tensor_arena[kTensorArenaSize];
}}

// Initialize TFLite
void setupTinyML() {{
  // Set up logging
  static tflite::MicroErrorReporter micro_error_reporter;
  error_reporter = &micro_error_reporter;
  
  // Load model
  model = tflite::GetModel(model_data);
  if (model->version() != TFLITE_SCHEMA_VERSION) {{
    Serial.println("Model schema mismatch!");
    return;
  }}
  
  // Create interpreter
  static tflite::AllOpsResolver resolver;
  static tflite::MicroInterpreter static_interpreter(
    model, resolver, tensor_arena, kTensorArenaSize, error_reporter
  );
  interpreter = &static_interpreter;
  
  // Allocate tensors
  TfLiteStatus allocate_status = interpreter->AllocateTensors();
  if (allocate_status != kTfLiteOk) {{
    Serial.println("AllocateTensors() failed!");
    return;
  }}
  
  // Get input/output tensors
  input = interpreter->input(0);
  output = interpreter->output(0);
  
  Serial.println("✓ TinyML initialized");
  Serial.print("  Input shape: ");
  Serial.print(input->dims->data[1]);
  Serial.print(" x ");
  Serial.println(input->dims->data[2]);
  Serial.print("  Arena used: ");
  Serial.print(interpreter->arena_used_bytes());
  Serial.println(" bytes");
}}

// Normalize input features
void normalizeFeatures(float* features, int n_features) {{
  for (int i = 0; i < n_features; i++) {{
    features[i] = (features[i] - feature_mins[i]) / feature_ranges[i];
  }}
}}

// Predict soil moisture
float predictSoilMoisture(
  float temp_history[],
  float humidity_history[],
  float light_history[],
  float hour_history[],
  int lookback
) {{
  // Fill input tensor
  for (int t = 0; t < lookback; t++) {{
    float features[4] = {{
      temp_history[t],
      humidity_history[t],
      light_history[t],
      hour_history[t]
    }};
    
    // Normalize
    normalizeFeatures(features, 4);
    
    // Copy to input tensor
    input->data.f[t * 4 + 0] = features[0];
    input->data.f[t * 4 + 1] = features[1];
    input->data.f[t * 4 + 2] = features[2];
    input->data.f[t * 4 + 3] = features[3];
  }}
  
  // Run inference
  unsigned long start = micros();
  TfLiteStatus invoke_status = interpreter->Invoke();
  unsigned long duration = micros() - start;
  
  if (invoke_status != kTfLiteOk) {{
    Serial.println("Invoke failed!");
    return -1;
  }}
  
  // Get prediction
  float prediction = output->data.f[0];
  
  Serial.print("Inference time: ");
  Serial.print(duration / 1000.0);
  Serial.println(" ms");
  
  return prediction;
}}
"""
    
    with open('models/tinyml_inference.ino', 'w') as f:
        f.write(code)
    
    print("✓ Arduino code saved: models/tinyml_inference.ino")


def main():
    """Main conversion pipeline"""
    
    print("=" * 60)
    print("TensorFlow Lite Conversion for ESP32")
    print("=" * 60)
    
    # Check if model exists
    if not os.path.exists('models/soil_moisture_model.h5'):
        print("❌ Model not found! Run train_model.py first.")
        return
    
    # Load normalization parameters
    with open('models/normalization_params.json', 'r') as f:
        norm_params = json.load(f)
    
    # Convert to TFLite (float32)
    tflite_model, size_float = convert_to_tflite(
        'models/soil_moisture_model.h5',
        'models/model.tflite',
        quantize=False
    )
    
    # Convert to TFLite (quantized)
    tflite_model_quant, size_quant = convert_to_tflite(
        'models/soil_moisture_model.h5',
        'models/model_quantized.tflite',
        quantize=True
    )
    
    # Test models
    test_input = np.random.randn(1, 4, 4).astype(np.float32)
    
    print("\n--- Testing Float32 Model ---")
    output_float = test_tflite_model('models/model.tflite', test_input)
    
    print("\n--- Testing Quantized Model ---")
    output_quant = test_tflite_model('models/model_quantized.tflite', test_input)
    
    # Compare outputs
    diff = abs(output_float[0][0] - output_quant[0][0])
    print(f"\nQuantization error: {diff:.4f}%")
    
    # Generate C header (use quantized model)
    generate_c_array(tflite_model_quant, 'models/model_data.h')
    
    # Generate Arduino code
    generate_arduino_code(norm_params)
    
    # Summary
    print("\n" + "=" * 60)
    print("Conversion Complete!")
    print("=" * 60)
    print(f"Float32 model: {size_float:.2f} KB")
    print(f"Quantized model: {size_quant:.2f} KB")
    print(f"Size reduction: {(1 - size_quant/size_float)*100:.1f}%")
    print("\nFiles generated:")
    print("  - models/model.tflite")
    print("  - models/model_quantized.tflite")
    print("  - models/model_data.h")
    print("  - models/tinyml_inference.ino")
    print("\nNext step: Copy model_data.h to edge/include/")


if __name__ == "__main__":
    main()
